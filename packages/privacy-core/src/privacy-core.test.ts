import { describe, expect, it } from "vitest";
import fc from "fast-check";
import type { AudienceContext, SensitiveField } from "../../contracts/src/index.js";
import {
  classifyStructuredRecord,
  classifyStructuredRecordWithAssistant,
  DeletionCoordinator,
  evaluateAudiencePolicy,
  explainPrivacyDecision,
  HandoffError,
  InMemoryHandoffStore,
  knownSensitivityRules,
  restrictPolicyWithAuthorizer,
  routeOutput
} from "./index.js";

const sharedAlice: AudienceContext = {
  profileId: "alice",
  profileType: "ADULT",
  identityConfidence: 0.98,
  deviceContext: "SHARED",
  roomName: "Living Room"
};

const privateAlice: AudienceContext = {
  ...sharedAlice,
  deviceContext: "PRIVATE",
  roomName: "Alice's Bedroom"
};

const healthFields: SensitiveField[] = [
  {
    path: "appointmentType",
    value: "QB_SECRET_HEALTH_7X9",
    category: "HEALTH",
    source: "test"
  },
  { path: "startsAt", value: "Friday at 3 PM", category: "PERSONAL", source: "test" },
  { path: "accessToken", value: "QB_SECRET_AUTH_4K2", category: "AUTH_SECRET", source: "test" }
];

describe("Sensitivity Map", () => {
  const fieldCases = Object.entries(knownSensitivityRules());

  it("contains at least 30 explicit invented-field rules", () => {
    expect(fieldCases.length).toBeGreaterThanOrEqual(30);
  });

  it.each(fieldCases)("classifies %s as %s", (path, expectedCategory) => {
    const result = classifyStructuredRecord({ [path]: `invented-${path}-value` }, "test");
    expect(result.fields).toHaveLength(1);
    expect(result.fields[0]).toMatchObject({ path, category: expectedCategory });
    expect(result.unknownPaths).toEqual([]);
  });

  it("fails closed for every unknown field generated by property testing", () => {
    const known = new Set(Object.keys(knownSensitivityRules()));
    fc.assert(
      fc.property(
        fc.string({ minLength: 1, maxLength: 30 }).filter((path) => !known.has(path)),
        fc.string(),
        (path, value) => {
          const result = classifyStructuredRecord({ [path]: value }, "fuzz");
          expect(result.fields[0]?.category).toBe("PERSONAL");
          expect(result.unknownPaths).toEqual([path]);
        }
      ),
      { numRuns: 1_000 }
    );
  });

  it("accepts only high-confidence, non-public assistant escalation for unknown metadata", async () => {
    const assistant = {
      async classify(input: { path: string; source: string; recordType: string }) {
        expect(input).toEqual({
          path: "carePlanReference",
          source: "calendar",
          recordType: "appointment"
        });
        return {
          category: "HEALTH" as const,
          confidence: 0.98,
          provider: "AWS_BEDROCK" as const,
          modelId: "test-model"
        };
      }
    };
    const result = await classifyStructuredRecordWithAssistant(
      { carePlanReference: "value-never-sent-to-assistant" },
      "calendar",
      "appointment",
      assistant
    );

    expect(result.fields[0]?.category).toBe("HEALTH");
    expect(result.assistTrace).toMatchObject({
      used: true,
      assistedPaths: ["carePlanReference"],
      valuesSent: false
    });
  });

  it("fails closed when an assistant tries to downgrade unknown metadata to public", async () => {
    const result = await classifyStructuredRecordWithAssistant(
      { novelField: "private value" },
      "calendar",
      "appointment",
      {
        async classify() {
          return {
            category: "PUBLIC" as const,
            confidence: 1,
            provider: "AWS_BEDROCK" as const,
            modelId: "test-model"
          };
        }
      }
    );

    expect(result.fields[0]?.category).toBe("PERSONAL");
    expect(result.assistTrace.failedPaths).toEqual(["novelField"]);
  });
});

describe("Audience Policy and Output Router", () => {
  const categoryExpectations = {
    PUBLIC: { shared: "PUBLIC", private: "PUBLIC", unknown: "PUBLIC", child: "PUBLIC", guest: "PUBLIC" },
    PERSONAL: { shared: "REDACTED", private: "PUBLIC", unknown: "BLOCKED", child: "BLOCKED", guest: "BLOCKED" },
    FINANCIAL: { shared: "PRIVATE", private: "PUBLIC", unknown: "BLOCKED", child: "BLOCKED", guest: "BLOCKED" },
    HEALTH: { shared: "PRIVATE", private: "PUBLIC", unknown: "BLOCKED", child: "BLOCKED", guest: "BLOCKED" },
    AUTH_SECRET: { shared: "REDACTED", private: "PUBLIC", unknown: "BLOCKED", child: "BLOCKED", guest: "BLOCKED" }
  } as const;

  it.each(Object.entries(categoryExpectations))(
    "exhaustively applies the audience matrix for %s",
    (category, expected) => {
      const fields: SensitiveField[] = [
        { path: "field", value: "QB_SECRET_MATRIX", category: category as SensitiveField["category"], source: "test" }
      ];
      const audiences = {
        shared: sharedAlice,
        private: privateAlice,
        unknown: { ...sharedAlice, profileType: "UNKNOWN" as const },
        child: { ...sharedAlice, profileType: "CHILD" as const },
        guest: { ...sharedAlice, profileType: "GUEST" as const }
      };

      for (const [context, audience] of Object.entries(audiences)) {
        const result = evaluateAudiencePolicy({
          fields,
          audience,
          resourceOwnerProfileId: "alice"
        });
        expect(result.decision, `${category}/${context}`).toBe(expected[context as keyof typeof expected]);
      }
    }
  );

  it("routes health details privately on a shared device", () => {
    const policy = evaluateAudiencePolicy({
      fields: healthFields,
      audience: sharedAlice,
      resourceOwnerProfileId: "alice"
    });
    const routed = routeOutput(healthFields, policy);
    expect(policy.decision).toBe("PRIVATE");
    expect(routed.spokenText).not.toContain("QB_SECRET_HEALTH_7X9");
    expect(routed.spokenText).not.toContain("QB_SECRET_AUTH_4K2");
    expect(routed.privateFields.map((field) => field.path)).not.toContain("accessToken");
  });

  it("permits non-secret details for a recognized adult on a private device", () => {
    const policy = evaluateAudiencePolicy({
      fields: healthFields,
      audience: privateAlice,
      resourceOwnerProfileId: "alice"
    });
    const routed = routeOutput(healthFields, policy);
    expect(policy.decision).toBe("PUBLIC");
    expect(routed.spokenText).toContain("QB_SECRET_HEALTH_7X9");
    expect(routed.spokenText).not.toContain("QB_SECRET_AUTH_4K2");
  });

  it.each([
    [{ ...sharedAlice, profileType: "UNKNOWN" as const }, "BLOCKED"],
    [{ ...sharedAlice, profileType: "GUEST" as const }, "BLOCKED"],
    [{ ...sharedAlice, profileType: "CHILD" as const }, "BLOCKED"],
    [{ ...sharedAlice, identityConfidence: 0.2 }, "BLOCKED"],
    [{ ...sharedAlice, profileId: "bob" }, "BLOCKED"]
  ])("blocks unsafe audience context %#", (audience, decision) => {
    expect(
      evaluateAudiencePolicy({
        fields: healthFields,
        audience,
        resourceOwnerProfileId: "alice"
      }).decision
    ).toBe(decision);
  });

  it("explains the category and context without repeating the hidden value", () => {
    const explanation = explainPrivacyDecision(["HEALTH_DATA", "SHARED_DEVICE"]);
    expect(explanation).toContain("health information");
    expect(explanation).toContain("shared");
    expect(explanation).not.toContain("QB_SECRET_HEALTH_7X9");
  });

  it("allows external authorization only to retain or restrict the local decision", async () => {
    const local = evaluateAudiencePolicy({
      fields: healthFields,
      audience: privateAlice,
      resourceOwnerProfileId: "alice"
    });
    const input = {
      profileId: "alice",
      profileType: "ADULT" as const,
      identityConfidence: 0.98,
      deviceContext: "PRIVATE" as const,
      ownerMatch: true,
      categories: ["HEALTH" as const],
      unknownFieldPresent: false
    };
    const allowed = await restrictPolicyWithAuthorizer(local, input, {
      async authorize() {
        return { decision: "ALLOW", provider: "AWS_VERIFIED_PERMISSIONS" };
      }
    });
    const denied = await restrictPolicyWithAuthorizer(local, input, {
      async authorize() {
        return { decision: "DENY", provider: "AWS_VERIFIED_PERMISSIONS" };
      }
    });
    const unavailable = await restrictPolicyWithAuthorizer(local, input, {
      async authorize() {
        throw new Error("service unavailable");
      }
    });

    expect(allowed.policy.decision).toBe("PUBLIC");
    expect(denied.policy.decision).toBe("BLOCKED");
    expect(denied.policy.reasons).toContain("EXTERNAL_POLICY_DENY");
    expect(unavailable.policy.decision).toBe("BLOCKED");
    expect(unavailable.policy.reasons).toContain("EXTERNAL_POLICY_UNAVAILABLE");
  });
});

describe("Authenticated private handoff", () => {
  it("is profile-bound, expires, works once, and never returns AUTH_SECRET fields", () => {
    let now = 1_000;
    const store = new InMemoryHandoffStore(100, () => now);
    const created = store.create({ requestId: "request-1", profileId: "alice", fields: healthFields });

    expect(() => store.consume(created.token, "bob")).toThrowError(HandoffError);
    const first = store.consume(created.token, "alice");
    expect(first.fields.map((field) => field.path)).toContain("appointmentType");
    expect(first.fields.map((field) => field.path)).not.toContain("accessToken");
    expect(() => store.consume(created.token, "alice")).toThrowError(
      expect.objectContaining({ code: "ALREADY_USED" })
    );

    const expiring = store.create({ requestId: "request-2", profileId: "alice", fields: [] });
    now += 101;
    expect(() => store.consume(expiring.token, "alice")).toThrowError(
      expect.objectContaining({ code: "EXPIRED" })
    );
  });

  it("allows only one of two immediate consume attempts", async () => {
    const store = new InMemoryHandoffStore();
    const created = store.create({ requestId: "request-1", profileId: "alice", fields: healthFields });
    const attempts = await Promise.allSettled([
      Promise.resolve().then(() => store.consume(created.token, "alice")),
      Promise.resolve().then(() => store.consume(created.token, "alice"))
    ]);
    expect(attempts.filter((attempt) => attempt.status === "fulfilled")).toHaveLength(1);
    expect(attempts.filter((attempt) => attempt.status === "rejected")).toHaveLength(1);
  });
});

describe("Deletion coordinator", () => {
  it("requires confirmation, deletes locally, revokes handoffs, and reports partial failure", async () => {
    const localIds = new Set(["request-1"]);
    const localStore = { deleteRequest: (id: string) => localIds.delete(id) };
    const handoffs = new InMemoryHandoffStore();
    const created = handoffs.create({ requestId: "request-1", profileId: "alice", fields: healthFields });
    const connector = { deleteRequest: async () => "FAILED_RETRYABLE" as const };
    const deletion = new DeletionCoordinator(localStore, handoffs, connector);

    const unconfirmed = await deletion.deleteRequest("request-1", false);
    expect(unconfirmed.state).toBe("CONFIRM_REQUIRED");
    expect(localIds.has("request-1")).toBe(true);

    const result = await deletion.deleteRequest("request-1", true);
    expect(result.local).toBe("DELETED");
    expect(result.connector).toBe("FAILED_RETRYABLE");
    expect(result.message).not.toContain("deleted everywhere");
    expect(() => handoffs.consume(created.token, "alice")).toThrowError(
      expect.objectContaining({ code: "INVALID" })
    );
  });
});
